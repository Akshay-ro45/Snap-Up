import type { Metadata } from 'next';

/**
 * Where the app is served from, for absolute URLs in metadata — canonical links, Open
 * Graph, the sitemap. Social crawlers and search engines need absolute URLs and cannot
 * resolve a relative one against anything.
 *
 * NEXT_PUBLIC_APP_URL is already set on the deployment (the entrance poster prints it into
 * its QR code). When it is missing, localhost is used so development works with nothing
 * configured; a production deploy without it would advertise localhost in its previews,
 * which is why it is listed as required in .env.example.
 */
export const SITE_URL = (process.env.NEXT_PUBLIC_APP_URL ?? 'http://localhost:3000').replace(/\/$/, '');

export const SITE_NAME = 'SnapUp';
export const DEFAULT_TITLE = 'SnapUp — Scan, Pay & Skip the Line';
export const DEFAULT_DESCRIPTION = 'Scan barcodes, build your cart, and check out without the queue.';

/** Generated by app/opengraph-image.tsx at build time. */
const SHARE_IMAGE = {
  url: '/opengraph-image',
  width: 1200,
  height: 630,
  alt: DEFAULT_TITLE,
};

interface PageSeo {
  /** Short page name; the root layout's template appends "· SnapUp". Omit for the home page. */
  title?: string;
  description: string;
  /** Path from the site root, e.g. "/guidelines". Becomes the canonical and og:url. */
  path: string;
  /**
   * False for anything tied to a session, an account or a single basket — a crawler that
   * indexes a checkout or someone's bills page indexes an empty shell, and a search result
   * that lands on it is a dead end.
   */
  index?: boolean;
}

/**
 * Everything a page's <head> needs, from one call.
 *
 * Open Graph and Twitter are set in full on every page rather than inherited. In the App
 * Router a child's `openGraph` replaces the parent's wholesale, so a page that set only a
 * title would silently lose its image and URL; building the whole object here is what
 * keeps them consistent.
 */
export function pageMetadata({ title, description, path, index = true }: PageSeo): Metadata {
  const fullTitle = title ? `${title} · ${SITE_NAME}` : DEFAULT_TITLE;

  return {
    ...(title ? { title } : { title: { absolute: DEFAULT_TITLE } }),
    description,
    alternates: index ? { canonical: path } : undefined,
    robots: index ? undefined : { index: false, follow: false },
    openGraph: {
      type: 'website',
      siteName: SITE_NAME,
      locale: 'en_IN',
      url: path,
      title: fullTitle,
      description,
      images: [SHARE_IMAGE],
    },
    twitter: {
      card: 'summary_large_image',
      title: fullTitle,
      description,
      images: [SHARE_IMAGE.url],
    },
  };
}
